defmodule AshDoubleEntry.PrimaryReadTest do
  use ExUnit.Case, async: true

  defmodule Account do
    @moduledoc false
    use Ash.Resource,
      domain: nil,
      validate_domain_inclusion?: false,
      data_layer: AshPostgres.DataLayer,
      extensions: [AshDoubleEntry.Account]

    postgres do
      table "accounts"
      repo(AshDoubleEntry.Test.Repo)
    end

    account do
      pre_check_identities_with AshDoubleEntry.Test.Domain
      transfer_resource AshDoubleEntry.Test.Transfer
      balance_resource AshDoubleEntry.Test.Balance
    end

    actions do
      defaults [:read]
    end
  end

  defmodule Balance do
    @moduledoc false
    use Ash.Resource,
      domain: nil,
      validate_domain_inclusion?: false,
      data_layer: AshPostgres.DataLayer,
      extensions: [AshDoubleEntry.Balance]

    postgres do
      table "balances"
      repo(AshDoubleEntry.Test.Repo)
    end

    balance do
      pre_check_identities_with AshDoubleEntry.Test.Domain
      transfer_resource AshDoubleEntry.Test.Transfer
      account_resource AshDoubleEntry.Test.Account
    end

    actions do
      defaults [:read]
    end
  end

  for resource <- [Account, Balance] do
    test "a read from `defaults` stays the primary read of #{inspect(resource)}" do
      assert Ash.Resource.Info.primary_action(unquote(resource), :read).name == :read
      refute Ash.Resource.Info.action(unquote(resource), :_autogenerated_primary_read)
    end
  end
end
